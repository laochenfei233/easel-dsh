/**
 * Build the plugin's client bundle.
 *
 * 1. Scope Easel's two global stylesheets under `.easel-scope` (tools/scope-css.mjs)
 *    and emit them as a JS string module the client imports.
 * 2. Bundle src/client.tsx into client.js — a classic script that registers the
 *    whole client through `window.__ModuleLoader__.load`. React and its jsx
 *    runtime stay external: the host seeds them, and two React copies would
 *    break hooks. marked/dompurify resolve from the dsh worktree's node_modules
 *    and are bundled in.
 */
import { createRequire } from 'node:module'
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { pathToFileURL } from 'node:url'
import { scopeCss } from './tools/scope-css.mjs'

const here = dirname(fileURLToPath(import.meta.url))
// Styles live inside the plugin since the Easel web frontend retired
// (easel-mac-package vendoring); apple.css was already authored here.
const EASEL_SRC = join(here, 'src')
// Easel repo layout keeps the plugin at ../dsh-plugin-easel beside dsh/, while
// the dsh-bundled staging (dsh/easel/dsh-plugin-easel) only has the dsh root as
// an ancestor, so resolve both instead of assuming one.
function resolveDshRoot() {
  if (existsSync(join(here, '..', 'dsh', 'apps', 'desktop-tauri'))) {
    return join(here, '..', 'dsh')
  }
  for (let dir = here; ; dir = dirname(dir)) {
    if (dir === dirname(dir)) break
    if (existsSync(join(dir, 'apps', 'desktop-tauri'))) return dir
  }
  throw new Error('dsh worktree root not found next to or above the plugin')
}
const DSH_ROOT = resolveDshRoot()

async function loadEsbuild() {
  const dshRequire = createRequire(join(DSH_ROOT, 'package.json'))
  try {
    return dshRequire('esbuild')
  } catch {
    // pnpm keeps bare requires honest; walk the store as a fallback.
    const store = join(DSH_ROOT, 'node_modules', '.pnpm')
    const dir = readdirSync(store).find((name) => name.startsWith('esbuild@'))
    if (dir === undefined) throw new Error('esbuild is not resolvable from the dsh worktree; run its install first')
    const mod = await import(pathToFileURL(join(store, dir, 'node_modules', 'esbuild', 'lib', 'main.js')).href)
    return mod.default ?? mod
  }
}

const esbuild = await loadEsbuild()

// 1. scoped stylesheets → src/generated/easel-css.js
// apple.css is authored in Easel's idiom and goes through the same scoping,
// appended last so its design layer wins by order at equal specificity.
const theme = readFileSync(join(EASEL_SRC, 'styles', 'theme.css'), 'utf8')
const index = readFileSync(join(EASEL_SRC, 'styles', 'index.css'), 'utf8')
const apple = readFileSync(join(here, 'src', 'styles', 'apple.css'), 'utf8')
const easelCss = `${scopeCss(theme)}\n${scopeCss(index)}\n${scopeCss(apple)}`
const generatedDir = join(here, 'src', 'generated')
mkdirSync(generatedDir, { recursive: true })
writeFileSync(
  join(generatedDir, 'easel-css.js'),
  '// GENERATED by build.mjs — do not edit. Easel\'s scoped stylesheets as one string.\n'
  + `export const EASEL_CSS = ${JSON.stringify(easelCss)};\n`,
)

// 2. client bundle — esbuild compiles, Node writes (esbuild's own writer can
// hit Access-denied on this hardlinked-then-deleted name).
const result = await esbuild.build({
  entryPoints: [join(here, 'src', 'client.tsx')],
  outfile: join(here, 'client.js'),
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  jsx: 'automatic',
  external: ['react', 'react/jsx-runtime'],
  // marked/dompurify 从 dsh 工作树的 pnpm store 解析（B4 后 Easel 前端只剩样式源，无 node_modules）。
  nodePaths: ['marked', 'dompurify'].map((pkg) => {
    const store = join(DSH_ROOT, 'node_modules', '.pnpm')
    const dir = readdirSync(store).find((name) => name.startsWith(`${pkg}@`))
    if (dir === undefined) throw new Error(`${pkg} is not resolvable from the dsh worktree; run its install first`)
    return join(store, dir, 'node_modules')
  }),
  // Wrap the CJS bundle as one __ModuleLoader__ registration. The banner
  // provides the CJS `module`/`exports` pair and the loader's `require`; the
  // footer hands the module's default export back as the plugin descriptor.
  banner: { js: "window.__ModuleLoader__.load({\n  id: 'dsh-plugin-easel',\n  factory(require) {\n    const module = { exports: {} };\n    const exports = module.exports;\n" },
  footer: { js: "\n    return module.exports.default ?? module.exports;\n  },\n})\n" },
  legalComments: 'none',
  logLevel: 'info',
  write: false,
})
if (result.errors.length > 0) {
  process.exitCode = 1
} else {
  for (const file of result.outputFiles) {
    writeFileSync(file.path, file.contents)
  }
}
